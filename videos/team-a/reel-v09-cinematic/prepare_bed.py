#!/usr/bin/env python3
"""One-time deterministic preparation of the committed, sidechain-ducked hotel bed.

Run after make_sound.py --out TMP. The offline render uses the resulting FLAC and
mapping, not this preparation step or Edge TTS. Adapted from grade's House Look
look/house_audio.py at commit 90394d8; original music and Foley are local.
"""
import argparse,hashlib,json,math,re,subprocess,wave
from pathlib import Path
import numpy as np
from scipy import signal
from scipy.io import wavfile
ROOT=Path(__file__).resolve().parent;SR=48000;N=60*SR

def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def decode(p):
    b=subprocess.check_output(['ffmpeg','-v','error','-i',str(p),'-ac','2','-ar',str(SR),'-f','s16le','-'])
    x=np.frombuffer(b,dtype='<i2').reshape(-1,2).astype(np.float32)/32767.0
    return np.pad(x,((0,max(0,N-len(x))),(0,0)))[:N]
def rms(x):return float(np.sqrt(np.mean(x.astype(np.float64)**2)))
def main():
    p=argparse.ArgumentParser();p.add_argument('--out',required=True,type=Path);a=p.parse_args();tmp=a.out;tmp.mkdir(parents=True,exist_ok=True)
    voicep=ROOT/'audio/narration_stem_48k.flac';bedp=ROOT/'audio/bed_ducked_48k.flac'
    voice=decode(voicep);raw=decode(tmp/'music.wav')+decode(tmp/'foley.wav')
    events=json.loads((ROOT/'timing/word_timings.json').read_text())['words'];gate=np.zeros(N,np.float32)
    for w in events:gate[max(0,round(w['start']*SR)):min(N,round(w['end']*SR))]=1
    sos=signal.butter(1,3.2,btype='lowpass',fs=SR,output='sos')
    smooth=np.clip(signal.sosfilt(sos,gate).astype(np.float32),0,1)
    shape=(1.65-.65*smooth)[:,None];shaped=raw*shape;active=gate>.5
    factor=rms(voice[active])/(rms(shaped[active])*10**(10.5/20));bed=shaped*factor
    bedwav=tmp/'bed-ducked.wav';wavfile.write(bedwav,SR,np.rint(np.clip(bed,-.999,.999)*32767).astype(np.int16))
    subprocess.run(['ffmpeg','-v','error','-y','-i',str(bedwav),'-c:a','flac','-compression_level','12',str(bedp)],check=True)
    bed=decode(bedp);ratio=20*math.log10(rms(voice[active])/rms(bed[active]));assert 8<=ratio<=12
    mix=voice+bed;peak=float(np.max(np.abs(mix)));pre_scale=min(1.0,.89/peak)
    pre=tmp/'mix-pre.wav';wavfile.write(pre,SR,np.rint(np.clip(mix*pre_scale,-1,1)*32767).astype(np.int16))
    run=subprocess.run(['ffmpeg','-hide_banner','-nostats','-i',str(pre),'-af','loudnorm=I=-16:TP=-2.2:LRA=9:print_format=json','-f','null','-'],capture_output=True,text=True,check=True)
    stats=json.loads(re.findall(r'\{\s*"input_i".*?\}',run.stderr,re.S)[-1])
    filt=('loudnorm=I=-16:TP=-2.2:LRA=9:linear=true:print_format=summary:'+
          ':'.join(f'{k}={stats[v]}' for k,v in [('measured_I','input_i'),('measured_TP','input_tp'),('measured_LRA','input_lra'),('measured_thresh','input_thresh'),('offset','target_offset')])+
          ',alimiter=limit=0.775:attack=3:release=40:level=false:latency=true,aresample=48000')
    master=tmp/'master_audio_48k.wav'
    subprocess.run(['ffmpeg','-v','error','-y','-i',str(pre),'-af',filt,'-ar','48000','-ac','2','-c:a','pcm_s16le',str(master)],check=True)
    windows=[]
    for start in range(0,60,10):
        sl=slice(start*SR,(start+10)*SR);m=active[sl];v=voice[sl];b=bed[sl]
        windows.append({'start_s':start,'end_s':start+10,'speech_duty':float(m.mean()),'voice_rms_all':rms(v),'bed_rms_all':rms(b),
                        'voice_minus_bed_active_db':20*math.log10(rms(v[m])/rms(b[m])) if m.any() else None})
    mapping={'source':'grade House Look ducking/master chain; original hotel background generated by make_sound.py',
      'stems_sha256':{voicep.name:sha(voicep),bedp.name:sha(bedp)},'master_wav_sha256':sha(master),
      'pre_scale':pre_scale,'bed_preparation_gain':factor,'speech_minus_combined_bed_db_active':ratio,
      'speech_active_seconds':float(active.sum()/SR),'six_10s_windows':windows,
      'first_loudnorm_measurement':stats,'loudnorm_filter':filt,
      'method':'Speech minus combined rain+score+Foley RMS on synthesizer word spans before common normalization; the duck curve is 3.2 Hz smoothed and the bed swells in pauses.'}
    (ROOT/'audio/gain_mapping.json').write_text(json.dumps(mapping,indent=2)+'\n')
    print('Prepared ducked bed; active speech margin',round(ratio,3),'dB; master SHA256',sha(master))
if __name__=='__main__':main()
